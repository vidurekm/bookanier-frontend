export function st(key: string, vars?: Record<string, string | number>) {
  const language = currentLanguage();
  let result: string;
  if (language === 'en') result = key;
  else if (language === 'cs') result = csTranslations[key] ?? tr(key);
  else {
    const translation = translations[key];
    result = translation?.[{ sk: 1, pl: 2 }[language]] ?? tr(key);
  }

  return vars ? result.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? '')) : result;
}

export function businessTypeLabel(key?: string | null, label?: string | null) {
  const translated: Record<string, string> = {
    SALON: st('Services with appointments'),
    RESTAURANT: st('Room and space bookings'),
    RENTAL: st('Equipment rentals'),
    EVENTS: st('Classes and events'),
    GENERAL: st('Other services'),
  };
  return (key && translated[key]) || label || st('Not configured');
}
